    "# ==============================================\n",
    "# SVHN-C CORRUPTION VALIDATION SCRIPT\n",
    "# ==============================================\n",
    "\n",
    "import numpy as np\n",
    "import tensorflow as tf\n",
    "import matplotlib.pyplot as plt\n",
    "import os\n",
    "\n",
    "# ==============================================\n",
    "# CONFIG\n",
    "# ==============================================\n",
    "\n",
    "MODEL_PATHS = {\n",
    "    \"M0\": \"models/svhn_seed0.h5\",\n",
    "    \"M1\": \"models/svhn_seed1.h5\",\n",
    "    \"M2\": \"models/svhn_seed2.h5\",\n",
    "    \"M3\": \"models/svhn_seed3.h5\",\n",
    "    \"M4\": \"models/svhn_seed4.h5\",\n",
    "}\n",
    "\n",
    "SVHNC_DIR = \"svhn_c\"\n",
    "\n",
    "CORRUPTIONS = [\n",
    "    \"gaussian_noise\",\"shot_noise\",\"impulse_noise\",\n",
    "    \"gaussian_blur\",\"motion_blur\",\"zoom_blur\",\n",
    "    \"fog\",\"snow\",\"spatter\",\n",
    "    \"brightness\",\"contrast\",\"jpeg_compression\",\n",
    "    \"translate\",\"rotate\",\"scale\"\n",
    "]\n",
    "\n",
    "SEVERITIES = [1,2,3,4,5]\n",
    "\n",
    "# ==============================================\n",
    "# LOAD MODELS\n",
    "# ==============================================\n",
    "\n",
    "models = {}\n",
    "for name, path in MODEL_PATHS.items():\n",
    "    models[name] = tf.keras.models.load_model(path, compile=False)\n",
    "    print(\"Loaded:\", name)\n",
    "\n",
    "model_list = list(models.values())\n",
    "\n",
    "# ==============================================\n",
    "# LOAD DATA\n",
    "# ==============================================\n",
    "\n",
    "def load_svhn_c(corruption, severity):\n",
    "    x = np.load(f\"{SVHNC_DIR}/{corruption}_{severity}.npy\")\n",
    "    y = np.load(f\"{SVHNC_DIR}/labels.npy\")\n",
    "    x = x.astype(\"float32\") / 255.0\n",
    "    return x, y\n",
    "\n",
    "# ==============================================\n",
    "# METRICS\n",
    "# ==============================================\n",
    "\n",
    "def accuracy(model, x, y):\n",
    "    pred = np.argmax(model.predict(x, verbose=0), axis=1)\n",
    "    return np.mean(pred == y)\n",
    "\n",
    "def agreement(models, x):\n",
    "    preds = []\n",
    "    for m in models:\n",
    "        p = np.argmax(m.predict(x, verbose=0), axis=1)\n",
    "        preds.append(p)\n",
    "    preds = np.stack(preds)\n",
    "    return np.mean(np.std(preds, axis=0) == 0)\n",
    "\n",
    "def confidence(model, x):\n",
    "    p = model.predict(x, verbose=0)\n",
    "    return np.mean(np.max(p, axis=1))\n",
    "\n",
    "# ==============================================\n",
    "# VISUAL CHECK\n",
    "# ==============================================\n",
    "\n",
    "def show_samples(x, y, title, n=8):\n",
    "    idx = np.random.choice(len(x), n, replace=False)\n",
    "    plt.figure(figsize=(12,3))\n",
    "    for i, j in enumerate(idx):\n",
    "        plt.subplot(1, n, i+1)\n",
    "        plt.imshow(x[j])\n",
    "        plt.title(y[j])\n",
    "        plt.axis(\"off\")\n",
    "    plt.suptitle(title)\n",
    "    plt.show()\n",
    "\n",
    "# ==============================================\n",
    "# MAIN VALIDATION LOOP\n",
    "# ==============================================\n",
    "\n",
    "results = []\n",
    "\n",
    "for c in CORRUPTIONS:\n",
    "    for s in SEVERITIES:\n",
    "\n",
    "        path = f\"{SVHNC_DIR}/{c}_{s}.npy\"\n",
    "        if not os.path.exists(path):\n",
    "            print(\"\\u274c Missing:\", path)\n",
    "            continue\n",
    "\n",
    "        x, y = load_svhn_c(c, s)\n",
    "\n",
    "        # Metrics\n",
    "        acc = accuracy(models[\"M0\"], x, y)\n",
    "        agr = agreement(model_list, x)\n",
    "        conf = confidence(models[\"M0\"], x)\n",
    "\n",
    "        results.append([c, s, acc, agr, conf])\n",
    "\n",
    "        print(f\"{c:20s} | S{s} | Acc={acc:.3f} | Agr={agr:.3f} | Conf={conf:.3f}\")\n",
    "\n",
    "        # Show only extreme cases\n",
    "        if s == 5:\n",
    "            show_samples(x, y, f\"{c} (severity {s})\")\n",
    "\n",
    "# ==============================================\n",
    "# SUMMARY\n",
    "# ==============================================\n",
    "\n",
    "print(\"\\n==============================\")\n",
    "print(\" SUMMARY \")\n",
    "print(\"==============================\")\n",
    "\n",
    "for r in results:\n",
    "    c, s, acc, agr, conf = r\n",
    "\n",
    "    flag = \"OK\"\n",
    "\n",
    "    if acc < 0.2 or agr < 0.3:\n",
    "        flag = \"BAD\"\n",
    "    elif acc < 0.5:\n",
    "        flag = \"CHECK\"\n",
    "\n",
    "    print(f\"{c:20s} S{s} | Acc={acc:.3f} | Agr={agr:.3f} | Conf={conf:.3f} | {flag}\")"
